-- Shared finance journal for reimbursements and partner profit payouts.
alter table public.pos_expenses
  add column if not exists description text,
  add column if not exists paid_by uuid references public.pos_profiles(id),
  add column if not exists reimbursed_at timestamptz;

create table if not exists public.pos_finance_partners (
  profile_id uuid primary key references public.pos_profiles(id) on delete cascade,
  profit_share numeric(5,2) not null default 0 check (profit_share >= 0 and profit_share <= 100),
  created_at timestamptz not null default now()
);

create table if not exists public.pos_finance_transactions (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('reimbursement', 'partner_payout')),
  profile_id uuid not null references public.pos_profiles(id),
  amount numeric(12,2) not null check (amount > 0),
  description text,
  transaction_date date not null default current_date,
  created_by uuid not null default auth.uid() references public.pos_profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.pos_finance_settings (
  id boolean primary key default true check (id),
  locked_through date,
  updated_by uuid references public.pos_profiles(id),
  updated_at timestamptz not null default now()
);

create table if not exists public.pos_manual_sales (
  id bigint generated by default as identity primary key,
  sale_date date not null,
  amount numeric(12,2) not null check (amount > 0),
  payment text not null check (payment in ('cash', 'card')),
  description text not null,
  reason text not null,
  created_by uuid not null default auth.uid() references public.pos_profiles(id),
  created_at timestamptz not null default now()
);
insert into public.pos_finance_settings (id) values (true) on conflict (id) do nothing;

create index if not exists pos_expenses_paid_by_idx on public.pos_expenses(paid_by);
create index if not exists pos_finance_transactions_profile_date_idx on public.pos_finance_transactions(profile_id, transaction_date);

alter table public.pos_finance_partners enable row level security;
alter table public.pos_finance_transactions enable row level security;
alter table public.pos_finance_settings enable row level security;
alter table public.pos_manual_sales enable row level security;

