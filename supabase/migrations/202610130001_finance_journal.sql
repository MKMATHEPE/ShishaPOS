create or replace function private.enforce_finance_period_lock()
returns trigger language plpgsql security invoker set search_path = '' as $$
declare
  lock_date date;
  entry_date date;
begin
  select locked_through into lock_date from public.pos_finance_settings where id = true;
  if lock_date is null then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;
  entry_date := case
    when tg_table_name = 'pos_expenses' and tg_op = 'DELETE' then old.time::date
    when tg_table_name = 'pos_expenses' then new.time::date
    when tg_table_name = 'pos_manual_sales' and tg_op = 'DELETE' then old.sale_date
    when tg_table_name = 'pos_manual_sales' then new.sale_date
    when tg_op = 'DELETE' then old.transaction_date
    else new.transaction_date
  end;
  if entry_date <= lock_date then raise exception 'This accounting period is locked through %', lock_date; end if;
  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;

drop trigger if exists enforce_expense_period_lock on public.pos_expenses;
create trigger enforce_expense_period_lock before insert or update or delete on public.pos_expenses
for each row execute function private.enforce_finance_period_lock();
drop trigger if exists enforce_transaction_period_lock on public.pos_finance_transactions;
create trigger enforce_transaction_period_lock before insert or update or delete on public.pos_finance_transactions
for each row execute function private.enforce_finance_period_lock();
drop trigger if exists enforce_manual_sale_period_lock on public.pos_manual_sales;
create trigger enforce_manual_sale_period_lock before insert or update or delete on public.pos_manual_sales
for each row execute function private.enforce_finance_period_lock();
