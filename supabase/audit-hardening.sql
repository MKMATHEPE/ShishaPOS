begin;
alter policy orders_update on public.pos_orders using ((select private.is_pos_admin())) with check ((select private.is_pos_admin()));
drop policy if exists finance_settings_management on public.pos_finance_settings;
create policy finance_settings_read on public.pos_finance_settings for select to authenticated using ((select private.has_pos_permission('management')));
create policy finance_settings_admin_write on public.pos_finance_settings for all to authenticated using ((select private.is_pos_admin())) with check ((select private.is_pos_admin()));
create table public.pos_finance_partners (
 profile_id uuid primary key references public.pos_profiles(id) on delete cascade,
 profit_share numeric(5,2) not null default 0 check(profit_share between 0 and 100),
 created_at timestamptz not null default now()
);
create table public.pos_finance_transactions (
 id bigint generated by default as identity primary key,
 kind text not null check(kind in ('reimbursement','partner_payout')),
 profile_id uuid not null references public.pos_profiles(id),
 amount numeric(12,2) not null check(amount>0), description text,
 transaction_date date not null default current_date,
 created_by uuid not null default auth.uid() references public.pos_profiles(id),
 created_at timestamptz not null default now()
);
create table public.pos_manual_sales (
 id bigint generated by default as identity primary key,
 sale_date date not null, amount numeric(12,2) not null check(amount>0),
 payment text not null check(payment in ('cash','card')),
 description text not null, reason text not null,
 created_by uuid not null default auth.uid() references public.pos_profiles(id),
 created_at timestamptz not null default now()
);
alter table public.pos_finance_partners enable row level security;
alter table public.pos_finance_transactions enable row level security;
alter table public.pos_manual_sales enable row level security;
create policy finance_partners_read on public.pos_finance_partners for select to authenticated using ((select private.has_pos_permission('management')));
create policy finance_partners_admin on public.pos_finance_partners for all to authenticated using ((select private.is_pos_admin())) with check ((select private.is_pos_admin()));
create policy finance_transactions_read on public.pos_finance_transactions for select to authenticated using ((select private.has_pos_permission('management')));
create policy finance_transactions_admin_insert on public.pos_finance_transactions for insert to authenticated with check ((select private.is_pos_admin()) and created_by=(select auth.uid()));
create policy manual_sales_read on public.pos_manual_sales for select to authenticated using ((select private.has_pos_permission('management')));
create policy manual_sales_admin_insert on public.pos_manual_sales for insert to authenticated with check ((select private.is_pos_admin()) and created_by=(select auth.uid()));
revoke all on public.pos_finance_partners,public.pos_finance_transactions,public.pos_manual_sales from anon,authenticated;
grant select,insert,update,delete on public.pos_finance_partners to authenticated;
grant select,insert on public.pos_finance_transactions,public.pos_manual_sales to authenticated;
grant usage,select on sequence public.pos_finance_transactions_id_seq,public.pos_manual_sales_id_seq to authenticated;
create index pos_finance_transactions_profile_date_idx on public.pos_finance_transactions(profile_id,transaction_date);
create function private.check_admin_finance_period() returns trigger language plpgsql set search_path='' as $$
declare lock_date date; entry_date date;
begin
 select locked_through into lock_date from public.pos_finance_settings where id=true;
 if tg_table_name='pos_manual_sales' then entry_date:=new.sale_date; else entry_date:=new.transaction_date; end if;
 if lock_date is not null and entry_date<=lock_date then raise exception 'This accounting period is locked'; end if;
 return new;
end; $$;
create trigger manual_sale_period before insert on public.pos_manual_sales for each row execute function private.check_admin_finance_period();
create trigger transaction_period before insert on public.pos_finance_transactions for each row execute function private.check_admin_finance_period();
create table public.pos_diagnostics (
 id bigint generated always as identity primary key,
 user_id uuid not null references public.pos_profiles(id),
 recorded_at timestamptz not null default now(),
 event text not null check(event in ('error','save_failed','slow_screen','slow_request','page_load')),
 screen text not null check(screen in ('pos','delivered','stock','management','settings','login','app')),
 code text not null check(length(code)<=64 and code ~ '^[a-zA-Z0-9_.-]+$'),
 duration_ms integer check(duration_ms between 0 and 3600000)
);
create index pos_diagnostics_user_time on public.pos_diagnostics(user_id,recorded_at desc);
alter table public.pos_diagnostics enable row level security;
revoke all on public.pos_diagnostics from anon,authenticated;
grant select on public.pos_diagnostics to authenticated;
create policy diagnostics_admin_read on public.pos_diagnostics for select to authenticated using ((select private.is_pos_admin()));
create function public.record_pos_diagnostic(event_name text,screen_name text,error_code text,elapsed_ms integer default null)
returns void language plpgsql security definer set search_path='' as $$
begin
 if not private.is_active_pos_user() then raise exception 'Not authorized' using errcode='42501'; end if;
 perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text,14014));
 if (select count(*) from public.pos_diagnostics where user_id=auth.uid() and recorded_at>now()-interval '1 minute')>=30 then return; end if;
 insert into public.pos_diagnostics(user_id,event,screen,code,duration_ms) values(auth.uid(),event_name,screen_name,error_code,elapsed_ms);
 delete from public.pos_diagnostics where user_id=auth.uid() and id not in (select id from public.pos_diagnostics where user_id=auth.uid() order by id desc limit 200);
end; $$;
revoke all on function public.record_pos_diagnostic(text,text,text,integer) from public,anon;
grant execute on function public.record_pos_diagnostic(text,text,text,integer) to authenticated;
commit;
